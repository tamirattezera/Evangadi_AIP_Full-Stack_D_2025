import express from "express";

/**
 * ============================================================
 * PRODUCT ROUTER
 * ============================================================
 *
 * Responsible for product-related routes.
 * ============================================================
 */

// ============================================================
// 1. CREATE ROUTER
// ============================================================

const router = express.Router();

// ============================================================
// 2. GET /products
// ============================================================

router.get("/", (req, res) => {
  res.status(200).json({
    message: "Products endpoint",
    products: [],
  });
});

// ============================================================
// 3. GET /products/:id
// ============================================================

router.get("/:id", (req, res) => {
  const { id } = req.params;

  res.status(200).json({
    message: "Product retrieved",
    productId: id,
  });
});

// ============================================================
// 4. POST /products
// ============================================================

router.post("/", (req, res) => {
  const { name, price } = req.body;

  res.status(201).json({
    message: "Product created",
    product: {
      name,
      price,
    },
  });
});

// ============================================================
// 5. EXPORT ROUTER
// ============================================================

export default router;
