// ==========================================================
// NODE.JS URL MODULE
// QUERY PARAMETER MUTATION
// ==========================================================
//
// Purpose:
// Understand how URLSearchParams can mutate a URL.
//
// Methods:
//
// set()
// append()
// getAll()
// delete()
//
// ==========================================================

// ==========================================================
// 1. CREATE URL
// ==========================================================

const url = new URL("https://api.example.com/products?category=ai&page=2");

// ==========================================================
// 2. ACCESS SEARCH PARAMETERS
// ==========================================================

const searchParams = url.searchParams;

// ==========================================================
// 3. ORIGINAL URL
// ==========================================================

console.log("========================================");

console.log(" ORIGINAL URL ");

console.log("========================================");

console.log(url.href);

// ==========================================================
// 4. UPDATE EXISTING PARAMETER
// ==========================================================

searchParams.set("page", "3");

// ==========================================================
// 5. CREATE NEW PARAMETER
// ==========================================================

searchParams.set("limit", "20");

// ==========================================================
// 6. ADD MULTIPLE VALUES
// ==========================================================

searchParams.append("tag", "ai");

searchParams.append("tag", "nodejs");

searchParams.append("tag", "backend");

// ==========================================================
// 7. READ MULTIPLE VALUES
// ==========================================================

const tags = searchParams.getAll("tag");

// ==========================================================
// 8. REMOVE PARAMETER
// ==========================================================

searchParams.delete("limit");

// ==========================================================
// 9. DISPLAY RESULT
// ==========================================================

console.log("\n========================================");

console.log(" UPDATED URL ");

console.log("========================================");

console.log(url.href);

console.log("\n========================================");

console.log(" TAGS ");

console.log("========================================");

console.log(tags);

console.log("========================================");
