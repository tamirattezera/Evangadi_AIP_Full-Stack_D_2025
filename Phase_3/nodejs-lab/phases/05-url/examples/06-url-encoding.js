// ==========================================================
// NODE.JS URL MODULE
// LESSON 06 — URL ENCODING
// ==========================================================
//
// Scenario:
// Build a URL for an AI-powered search service.
//
// ==========================================================

// ==========================================================
// 1. USER INPUT
// ==========================================================

const searchQuery = "AI & Full-Stack Engineering";

// ==========================================================
// 2. CREATE API URL
// ==========================================================

const url = new URL("https://api.example.com/ai/search");

// ==========================================================
// 3. ADD USER INPUT SAFELY
// ==========================================================

url.searchParams.set("q", searchQuery);

// ==========================================================
// 4. DISPLAY URL
// ==========================================================

console.log("========================================");

console.log(" ENCODED API URL ");

console.log("========================================");

console.log(url.href);

// ==========================================================
// 5. READ THE ORIGINAL VALUE
// ==========================================================

const decodedQuery = url.searchParams.get("q");

console.log("\nDecoded query:");

console.log(decodedQuery);

console.log("========================================");
