console.log(path.sep);

// ========================================
// PATH DELIMITER
// ========================================

// The delimiter separates multiple paths.
//
// Linux/macOS -> ":"
// Windows     -> ";"
console.log("\nPath Delimiter:");
console.log(path.delimiter);
